def get_rate_emoji(score: int) -> str:
    if score <= 3:
        return "💀"
    if score <= 6:
        return "😐"
    if score <= 8:
        return "😎"
    return "🔥"


def get_luck_comment(percent: int) -> str:
    if percent <= 20:
        return "сегодня лучше не рисковать 💀"
    if percent <= 50:
        return "так себе, но жить можно 😐"
    if percent <= 80:
        return "день нормальный 😎"
    return "сегодня ты в ударе 🔥"


def load_roles() -> dict:
    try:
        with open(ROLES_FILE, "r", encoding="utf-8") as file:
            return json.load(file)
    except FileNotFoundError:
        return {}
    except json.JSONDecodeError:
        return {}


def save_roles(data: dict) -> None:
    with open(ROLES_FILE, "w", encoding="utf-8") as file:
        json.dump(data, file, ensure_ascii=False, indent=2)


def generate_daily_role() -> str:
    # редкое событие дня
    if random.randint(1, 100) <= 5:
        return random.choice(RARE_ROLE_EVENTS)

    player = random.choice(USERS)
    role_text = random.choice(DAILY_ROLES)
    event = random.choice(DAILY_EVENTS)

    text = (
        "🎭 Роль дня:\n\n"
        f"{player} — {role_text}\n"
        f"↳ {event}"
    )

    return text


